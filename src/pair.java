public class pair {
    private int v;
    private int weight;

    public pair(int weight, int v) {
        this.weight = weight;
        this.v = v;
    }

    public int getV() {
        return v;
    }

    public void setV(int v) {
        this.v = v;
    }

    public int getWeight() {
        return weight;
    }

    public void setWeight(int weight) {
        this.weight = weight;
    }
}
